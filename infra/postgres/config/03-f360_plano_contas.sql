-- Agrupador do plano de contas do F360 (PESSOAS, OCUPACAO, ADMINISTRATIVAS...), usado pela
-- Rentabilidade por Setor para separar as despesas por tipo (colunas vlrCusto<Agrupador> do Fato Item).
-- Rodado a cada deploy pelo db-setup como o papel config_app. Só "CREATE ... IF NOT EXISTS".
-- Origem: tabela f360planocontas do lakehouse do Fabric (planilha Files/F360/PlanoContas.xlsx),
-- lida pelo OneLake em 14/10/2026 (220 planos, versão Delta 149). A carga só inclui o que falta
-- (ON CONFLICT DO NOTHING): o que for editado no Directus prevalece. Plano novo no F360 sem linha
-- aqui aparece num teste do dbt (aviso) e deve ser incluído no Directus.
-- O rateio do F360 traz só o NOME do plano; a ligação é por nome.
CREATE TABLE IF NOT EXISTS config.f360_plano_contas (
    plano_de_contas_id  text PRIMARY KEY,          -- PlanoDeContasId do F360
    nome                text NOT NULL UNIQUE,      -- como vem no rateio das parcelas
    tipo                text,                      -- 'A pagar' | 'A receber'
    agrupador1          text NOT NULL,
    agrupador2          text,
    agrupador3          text,
    alterado_em         timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE config.f360_plano_contas IS 'Agrupadores do plano de contas do F360 (Rentabilidade por Setor)';

CREATE OR REPLACE TRIGGER f360_plano_contas_alterado_em
    BEFORE UPDATE ON config.f360_plano_contas
    FOR EACH ROW EXECUTE FUNCTION config.tocar_alterado_em();

